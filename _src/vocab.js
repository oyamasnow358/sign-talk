// → [{ id, cat, e, w, p, s, u }]
const VOCAB = (function () {
  const out = [], seen = {};
  VOCAB_CATS.forEach(c => VOCAB_SRC[c.id].trim().split('\n').forEach((line, i) => {
    const a = line.split('|');
    let id = c.id + '-' + a[1].replace(/\s+/g, '');
    while (seen[id]) id += '2';
    seen[id] = 1;
    out.push({ id, cat: c.id, e: a[0], w: a[1], p: a[2] || a[1], s: a[3] || '', u: (a[4] || '').indexOf('u') >= 0 });
  }));
  return out;
})();
